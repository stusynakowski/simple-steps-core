"""The handover, checked: everything the app asked core for, run.

Run it with ``.venv/bin/python tutorial/handover.py``. It walks
``core-handover/`` (the app's requirements, generated by the app repo) in
three parts, each line run against core:

    A. the acceptance session (core-handover/plan.md, "What should work"),
       line by line, on today's API (``Kernel`` and ``Catalog``, not ``grid``)
    B. the requests K19–K29, R7–R9 (core-handover/requests.md) and the
       "Fix in core" table (plan.md); K1–K18 are scripts/core_asks.py's
    C. the six probes (core-handover/probes/), ported: as written they import
       ``simple_steps_core.grid``, which is gone (docs/design/app-migration.md)

Each line prints ✓ (core does what was asked), ✗ (it doesn't yet; the note
names the decision or plan step) or ? (the ask was changed by a later
decision; the note says how). Where a later decision changed an ask, the
check is of the decision, and the note says so. tutorial/README.md §5 explains
the results. This file changes no behaviour; it only reports.
"""

from __future__ import annotations

import importlib
import warnings

import pandas as pd

from simple_steps_core import (Catalog, Kernel, Secret, bound_tool, cols, join, mod,
                               op, res, resource, stack, tool, wf, zip_)
from tutorial import RESULTS, chapter, data, lesson, problems, put

warnings.simplefilter("ignore")


# ── the acceptance session's tools ───────────────────────────────────────
@tool
def patients() -> pd.DataFrame:
    return pd.DataFrame({"name": ["Ana", "Ben", "Cy"], "temp_c": [36.6, 38.2, 37.1]})


@tool
def to_f(temp_c: float) -> float:
    return round(temp_c * 9 / 5 + 32, 2)


@tool
def feverish(temp_c: float, limit: float = 38) -> bool:
    return temp_c >= limit


@tool
def os_remove(path: str) -> None:                       # a tool, never in a catalog
    raise RuntimeError("must never run")


CAT = Catalog(tools=[patients, to_f, feverish])


def states(k: Kernel) -> dict:
    return {s.name: s.state for s in k.steps}


# ── A. the acceptance session ────────────────────────────────────────────
def part_a():
    chapter("A. The acceptance session (plan.md), on today's API")
    k = Kernel(CAT)
    lesson("A1", "a catalog object, and a kernel made from it",
           type(k).__name__, "Kernel")
    k["p"] = patients[mod.source()]()
    k["sick"] = feverish[mod.filter()](wf["p"])
    k["f"] = to_f[mod.map()](wf["sick"])
    lesson("A2", "source, filter, map declare; nothing runs",
           states(k), {"p": "staged", "sick": "staged", "f": "staged"})
    k["g"] = "to_f[mod.map()](wf['p'])"
    lesson("A3a", "a plain string stays a string value (EX13)", data(k.step("g"), "g"),
           ["to_f[mod.map()](wf['p'])"])
    del k["g"]
    from simple_steps_core import formula
    k["g"] = formula("to_f[mod.map()](wf['p'])")
    lesson("A3b", "formula(text) parses against the catalog (EX13)",
           (k.step("g").formula, k.step("g").state), ('to_f[mod.map()](wf["p"])', "staged"))
    del k["g"]
    lesson("A4", "validate(): {step: problems}, none here", {n: p for n, p in k.validate().items() if p}, {})
    k.run_all()
    text = repr(k)
    lesson("A5", "the kernel prints as a table: step, formula, state, shape",
           all(w in text for w in ("step", "formula", "state", "shape")), True)
    lesson("A6", "f's rows keep their ids: Ben is row 1 of p",
           list(k.step("f").data.index), [1])
    lesson("A7", "a step prints its formula back", k.step("f").formula, 'to_f[mod.map()](wf["sick"])')
    cell = k.cell("f", 0, "f")
    lesson("A8", "a cell: its value, its type and the input row it came from",
           (cell["value"], cell["type"], cell["inputs"][0]["values"]),
           (100.76, "float", {"temp_c": 38.2}))
    k["sick"] = feverish[mod.filter()](wf["p"], limit=37)
    lesson("A9", "an edit: sick stale; f read it stale (not passed down)",
           ({n: k.step(n).state for n in ("p", "sick", "f")}, k.needs_run().get("f")),
           ({"p": "completed", "sick": "stale", "f": "completed"}, "read stale 'sick'"))
    k["x"] = os_remove[mod.map()](wf["p"])
    lesson("A10", "a function not in the catalog is a problem and never runs",
           k.step("x").state, "invalid")
    del k["x"]
    k["late"] = to_f[mod.map()](wf["later"])
    lesson("A11", "a step reads only earlier steps", k.step("late").state, "invalid")
    del k["late"]
    s = put(k, "w", to_f[mod.map()](wf["p"], temp_c=wf["p"][cols["temp_c"]]))
    lesson("A12", "a column argument pairs per row (K19)", data(s, "w"), [97.88, 100.76, 98.78])
    k["srt"] = mod.sort(by="temp_c")(wf["p"])
    k["s"] = wf["srt"][0]
    k.run_all()
    first = data(k.step("s"), "name")
    k["srt"] = mod.sort(by="temp_c", ascending=False)(wf["p"])
    k.run_all()
    lesson("A13", "a pick is the same row after a re-sort (row id)",
           (first, data(k.step("s"), "name")), (["Ana"], ["Ana"]))
    k2 = Kernel.from_json(k.to_json(), CAT)
    k2.run_all()
    lesson("A14", "to_json, then from_json(text, catalog): the same data",
           data(k2.step("f"), "f"), data(k.step("f"), "f"))


# ── B. the requests, and the "Fix in core" table ─────────────────────────
def part_b():
    chapter("B. The requests (requests.md) and the Fix-in-core table (plan.md)")
    k = Kernel(CAT)
    k["p"] = patients[mod.source()]()
    k["sick"] = feverish[mod.filter()](wf["p"])
    k.run_all()

    # K19 — a column argument, and row ids
    s = put(k, "x1", feverish[mod.filter()](wf["p"], limit=wf["sick"][cols["temp_c"]]))
    lesson("K19a", "a column from a subset is refused, writing the join", s.state, "invalid",
           "K19 asked per row by type, by position; CA-11 (2026-11-02) made pairing by identity, "
           "only between aligned steps", open_=True)
    for name, ex in {"ex": op("identity")[mod.expand(columns=["lst"])](wf["pl"]),
                     "jn": join(wf["p"], wf["sick"], on="#p"),
                     "st": stack(wf["p"], wf["sick"])}.items():
        if name == "ex":
            k["pl"] = pd.DataFrame({"lst": [[1, 2], [3]]})
        put(k, name, ex)
    unique = all(k.step(n).data.index.is_unique for n in ("ex", "jn", "st", "p"))
    lesson("K19b", "rows made by expand, join, stack and a source have unique ids", unique, True)

    # K20 — identity
    a, b = Kernel(CAT), Kernel(CAT)
    for kk in (a, b):
        kk["p"] = patients[mod.source()]()
        kk["f"] = to_f[mod.map()](wf["p"])
    lesson("K20a", "two kernels with the same steps have the same id", a.id == b.id, True)
    b.rename("f", "g")
    lesson("K20b", "a step name is part of the id", a.id != b.id, True)
    lesson("K20c", "k.diff names the first step that differs", bool(a.diff(b)["steps"]), True)
    lesson("K20d", "each step has an id", bool(a.step("f").id), True)

    @tool
    def to_f2(temp_c: float) -> float:
        return temp_c * 2
    c1 = Kernel(Catalog(tools=[patients, to_f2]))
    c1["p"] = patients[mod.source()]()
    c1["f"] = to_f2[mod.map()](wf["p"])
    c1.run_all()
    text = c1.to_json()

    def edited():                                    # the same tool, its code changed
        @tool
        def to_f2(temp_c: float) -> float:
            return temp_c * 3
        return to_f2
    c2 = Kernel.from_json(text, Catalog(tools=[patients, edited()]))
    lesson("K20e", "a tool whose code changed: its id changes", c2.id != c1.id, True)

    @resource
    class Api:
        def __init__(self, url: str = "x", key: Secret[str] = ""):
            self.url, self.key = url, key

        @bound_tool
        def ping(self, name: str) -> str:
            return name

    r1, r2 = (Kernel(Catalog(tools=[patients], resources=[Api])) for _ in range(2))
    r1.define("api", Api, url="u", key="one")
    r2.define("api", Api, url="u", key="two")
    lesson("K20f", "a secret setting is left out of the id", r1.id == r2.id, True)

    # K21 — extras
    @tool(extras={"simple_steps.ui": {"temp_c": "slider"}})
    def to_c(temp_c: float) -> float:
        return temp_c
    xcat = Catalog(tools=[patients, to_c])
    x = Kernel(xcat)
    x["p"] = patients[mod.source()]()
    x["c"] = to_c[mod.map()](wf["p"])
    before = x.id
    x.step("c").extras["simple_steps.ui"] = {"color": "red"}
    lesson("K21", "extras are saved, and never hashed",
           (x.id == before, Kernel.from_json(x.to_json(), xcat).step("c").extras),
           (True, {"simple_steps.ui": {"color": "red"}}))

    # K22 — earlier outputs kept while something reads them
    kk = Kernel(CAT)
    kk["p"] = patients[mod.source()]()
    kk["lim"] = 38.0
    kk["s"] = feverish[mod.filter()](wf["p"], limit=wf["lim"])
    kk.run_all()
    before = kk.step("s").output
    kk["lim"] = 37.0
    shown = kk.step("s").output is before                 # stale, still showing what it read
    kk.run("s")
    kept = kk.workflow.results("s")
    lesson("K22", "a stale reader still shows the version it read; earlier results kept",
           (shown, len(kept), kept[1] is before), (True, 2, True),
           open_=False)

    # K23 — progress and cancel
    lesson("K23", "progress modifiers report each cell to a callback; cancel()",
           hasattr(Kernel, "cancel"), True, "not built (plan step D, K14)")

    # K24 — no shared state
    @tool
    def only_here(temp_c: float) -> float:
        return temp_c
    one = Kernel(Catalog(tools=[patients, only_here]))
    two = Kernel(CAT)
    two["p"] = patients[mod.source()]()
    two["o"] = only_here[mod.map()](wf["p"])
    lesson("K24a", "a tool in one kernel's catalog isn't usable in another's", two.step("o").state, "invalid")
    one["p"] = patients[mod.source()]()
    lesson("K24b", "two kernels in one process don't see each other's steps",
           ([s.name for s in one.steps], [s.name for s in two.steps]), (["p"], ["p", "o"]))
    gone = []
    for name in ("grid", "execution", "operations", "domain", "serving", "api", "loader", "app", "agent", "inspect"):
        try:
            importlib.import_module(f"simple_steps_core.{name}")
            gone.append(name)
        except ModuleNotFoundError:
            pass
    lesson("K24c", "the older engine's modules are gone (one model)", gone, [])

    # K25 — a resource reports a data version
    @resource
    class Db:
        version = 1

        def __init__(self, name: str = "db"):
            self.name = name

        def data_version(self) -> str:
            return str(Db.version)

        @bound_tool
        def look(self, name: str) -> str:
            return f"{name}@{Db.version}"
    d = Kernel(Catalog(tools=[patients], resources=[Db]))
    d["p"] = patients[mod.source()]()
    d.define("db", Db)
    d["l"] = res["db"].look[mod.map()](wf["p"])
    d.run_all()
    Db.version = 2
    lesson("K25", "a resource whose data version changes makes its readers stale",
           d.needs_run().get("l", "").startswith("stale"), True)

    # K26 — sizes
    k["m"] = to_f[mod.map()](wf["sick"])
    staged = k.step("m").plan["size"]
    k.run("m")
    ran = k.step("m").plan["size"]
    lesson("K26a", "before it runs: size unknown, with the reason",
           (staged["certainty"], bool(staged.get("because"))), ("unknown", True))
    lesson("K26b", "after it runs: rows and bytes", (ran["certainty"], ran["rows"], ran["bytes"] > 0), ("exact", 1, True))
    lesson("K26c", "one way to read a page", "rows" in k.view("p", rows=(0, 2)), True)

    # K27 — return types
    @tool
    def untyped(temp_c):
        return temp_c > 37
    u = Kernel(Catalog(tools=[patients, untyped]))
    u["p"] = patients[mod.source()]()
    u["t"] = untyped[mod.map()](wf["p"])
    before = u.step("t").plan.get("types", {})
    u.run_all()
    lesson("K27a", "an undeclared return type is unknown before it runs",
           str(before.get("t", before)).lower().count("unknown") > 0, True,
           "the plan doesn't state the type as unknown. EX11 (proposed 2026-11-03)")
    lesson("K27b", "after a run, the type observed", u.step("t").plan["types"].get("t"), "bool")

    # K28 — lineage
    k["two"] = op("identity")[mod.expand(columns=["lst"])](wf["pl"])
    k.run("two")
    lesson("K28a", "rows from expand map to their source row", data(k.step("two"), "#pl"), [0, 0, 1])
    lesson("K28b", "each output stores, per cell, the input cells it came from",
           "lineage" in k.step("m").output.meta, True,
           "worked out on request by k.cell, not stored. ST's row map is the stored part")

    # K29 — renames, and reading old data
    k.rename("sick", "ill")
    lesson("K29a", "a rename rewrites the references, and readers stay completed",
           (k.step("m").formula, k.step("m").state), ('to_f[mod.map()](wf["ill"])', "completed"))
    k["ill"] = feverish[mod.filter()](wf["p"], limit=37)
    k.run("m", fresh=False)                 # on purpose: run(m) alone would run ill first (C9)
    lesson("K29b", "a step that read old data warns, naming the step and version",
           len(k.step("m").warnings) > 0, True, "kept in output meta (read_stale), not a warning. SS7, SM")

    # R7–R9
    lesson("R7", "images and files as media handles, saved by content hash", False, True,
           "not built: ST piece 3 (agreed 2026-11-03)")

    @tool
    def risky(n: int) -> int:
        if n % 2 == 0:
            raise ValueError("even")
        return n * 100
    r = Kernel(Catalog(tools=[risky]))
    r["n"] = pd.DataFrame({"n": [1, 2, 3, 2]})
    r["out"] = risky[mod.map(), mod.try_except()](wf["n"])
    r.run_all()
    lesson("R8", "failed rows keep an int column int", str(r.step("out").data["out"].dtype), "Int64")
    lesson("R9", "stages: a named group of steps that runs as one", hasattr(Kernel, "run_stage"), True,
           "not built, though model.md §3 said built: corrected")

    # Fix-in-core rows not covered above
    lesson("F1", "problems are structured: code, message, step",
           all(hasattr(p, a) for p in k.check("zz", to_f[mod.map()](wf["nowhere"])) for a in ("code", "step")), True)
    lesson("F2", "specs: k.spec, step.spec, Kernel.from_spec",
           Kernel.from_spec(k.spec, CAT).spec == k.spec, True)
    lesson("F3", "a proposal is checked without adding it (proposals.py's check_step)",
           k.check("g2", to_f[mod.map()](wf["p"])), ())


# ── C. the probes, ported ─────────────────────────────────────────────────
def part_c():
    chapter("C. The handover's probes, ported off grid")

    @tool
    def make() -> pd.DataFrame:
        return pd.DataFrame({"n": [3, 1, 2], "w": [10, 20, 30]})

    @tool
    def make_w() -> pd.DataFrame:
        return pd.DataFrame({"weight": [10, 20, 30]})

    @tool
    def scale(n: int, weight: int = 1) -> int:
        return n * weight

    @tool
    def scale_untyped(n, weight=1):
        return n * weight

    @tool
    def dbl(n: int) -> int:
        return n * 2

    @tool
    def spread(n: int) -> list:
        return [n, n * 10]

    cat = Catalog(tools=[make, make_w, scale, scale_untyped, dbl, spread])

    def base():
        k = Kernel(cat)
        k["r"] = make[mod.source()]()
        k.run_all()
        return k

    # probe_colarg.py
    k = base()
    lesson("Pc1", "colarg: an untyped column argument pairs per row",
           data(put(k, "s", scale_untyped[mod.map()](wf["r"], weight=wf["r"][cols["w"]])), "s"), [30, 20, 60])
    lesson("Pc2", "colarg: a typed column argument pairs per row",
           data(put(k, "s2", scale[mod.map()](wf["r"], weight=wf["r"][cols["w"]])), "s2"), [30, 20, 60])
    lesson("Pc3", "colarg: the same with the verb inferred",
           data(put(k, "s3", scale(wf["r"], weight=wf["r"][cols["w"]])), "s3"), [30, 20, 60])
    # probe_colarg2.py
    k["w"] = make_w[mod.source()]()
    k.run_all()
    s = put(k, "z", zip_(wf["r"], wf["w"]))
    lesson("Pc4", "colarg2: zip_ of two unrelated sources is refused, naming the fixes", s.state, "invalid",
           "the handover's route ran by position; CA-11 refuses it: join on a key, or match_ids=True",
           open_=True)
    s = put(k, "z2", zip_(wf["r"], wf["w"], match_ids=True))
    # weight has a default, so z2's weight column is bound, not taken by name
    # (core-asks L50c, 2026-11-04): the handover's route relied on the name
    k["s4"] = scale[mod.map()](wf["z2"], weight=wf["z2"][cols["weight"]])
    k.run("s4")
    lesson("Pc5", "colarg2: vouched with match_ids, then a map", data(k.step("s4"), "s4"), [30, 20, 60])
    # probe_refs2.py
    k = base()
    lesson("Pr1", "refs: a selection as its own step", data(put(k, "a", wf["r"][0:2]), "n"), [3, 1])
    lesson("Pr2", "refs: a column as its own step", data(put(k, "b", wf["r"][cols["n"]])), {"n": [3, 1, 2]})
    lesson("Pr3", "refs: one cell as an argument",
           data(put(k, "c", scale[mod.map()](wf["r"], weight=wf["r"][0][cols["w"]])), "c"), [30, 10, 20])
    s = put(k, "d", op("identity")[mod.sort(by=wf["r"])](wf["r"]))
    lesson("Pr4", "refs: a step as a modifier setting is refused (modifiers take no data, D22)",
           getattr(s, "state", type(s).__name__) in ("invalid", "TypeError"), True)
    lesson("Pr5", "refs: a computed argument is a literal",
           data(put(k, "e", scale[mod.map()](wf["r"], weight=len("abc"))), "e"), [9, 3, 6])
    lesson("Pr6", "refs: a reference to a later step is refused",
           put(k, "f", scale[mod.map()](wf["later"])).state, "invalid")
    k["srt"] = op("identity")[mod.sort(by="n")](wf["r"])
    k.run_all()
    lesson("Pr7", "refs: row 0 of a sorted step is its first row",
           data(put(k, "g", wf["srt"][0][cols["w"]]), "w"), [20])
    # probe_rename_lineage.py
    k = Kernel(cat)
    k["p"] = pd.DataFrame({"n": [1, 2]})
    k["d"] = dbl[mod.map()](wf["p"])
    k.run_all()
    k.rename("p", "q")
    lesson("Pl1", "rename: references follow, d stays completed",
           (k.step("d").formula, k.step("d").state), ('dbl[mod.map()](wf["q"])', "completed"))
    k["e"] = spread[mod.expand()](wf["q"])
    k.run_all()
    lineage = [r["lineage"] for r in k.view("e")["rows"]]
    lesson("Pl2", "rename: an expand's rows trace to their parent (#q) and their place (#q.idx)",
           ([r["#q"] for r in lineage], [r["#q.idx"] for r in lineage]), ([0, 0, 1, 1], [0, 1, 0, 1]))
    # terminal_demo.py is part A; toolhash.py is K20e


def main() -> None:
    for part in (part_a, part_b, part_c):
        part()
    tally = {m: sum(1 for r in RESULTS if r[0] == m) for m in "✓✗?"}
    print(f"\n{len(RESULTS)} checks: {tally['✓']} ✓  {tally['✗']} ✗  {tally['?']} ?")


if __name__ == "__main__":
    main()
